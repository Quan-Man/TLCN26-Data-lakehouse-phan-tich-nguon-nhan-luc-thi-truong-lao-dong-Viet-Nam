-- Shared dimensions for the Vietnam labor-market warehouse.
CREATE TABLE IF NOT EXISTS gold.dim_date (
    date_key integer PRIMARY KEY, -- YYYYMMDD; use 0 for unknown if needed
    full_date date UNIQUE,
    day_of_month smallint CHECK (day_of_month BETWEEN 1 AND 31),
    day_of_week smallint CHECK (day_of_week BETWEEN 1 AND 7),
    day_name text,
    week_of_year smallint CHECK (week_of_year BETWEEN 1 AND 53),
    month_number smallint CHECK (month_number BETWEEN 1 AND 12),
    month_name text,
    quarter_number smallint CHECK (quarter_number BETWEEN 1 AND 4),
    year_number smallint,
    is_weekend boolean,
    is_holiday boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS gold.dim_location (
    location_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id text NOT NULL UNIQUE,
    location_name text NOT NULL,
    location_type text NOT NULL DEFAULT 'unknown',
    province_name text,
    region_name text,
    country_code char(2) NOT NULL DEFAULT 'VN',
    latitude numeric(9,6),
    longitude numeric(9,6),
    valid_from date,
    valid_to date,
    is_current boolean NOT NULL DEFAULT true,
    CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from)
);

CREATE TABLE IF NOT EXISTS gold.dim_company (
    company_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id text NOT NULL UNIQUE,
    company_name text NOT NULL,
    company_name_normalized text,
    website text,
    company_size text,
    industry_id text,
    is_active boolean NOT NULL DEFAULT true,
    source_name text
);

CREATE TABLE IF NOT EXISTS gold.dim_occupation (
    occupation_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occupation_id text NOT NULL UNIQUE,
    occupation_name text NOT NULL,
    occupation_group text,
    occupation_family text,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS gold.dim_industry (
    industry_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    industry_id text NOT NULL UNIQUE,
    industry_name text NOT NULL,
    parent_industry_id text,
    industry_level smallint,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS gold.dim_major (
    major_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    major_id text NOT NULL UNIQUE,
    major_name text NOT NULL,
    major_group text,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS gold.dim_skill (
    skill_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id text NOT NULL UNIQUE,
    skill_name text NOT NULL,
    skill_category text,
    skill_type text,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS gold.dim_university (
    university_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_id text NOT NULL UNIQUE,
    university_name text NOT NULL,
    university_name_normalized text,
    location_id text,
    institution_type text,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS gold.dim_economic_indicator (
    economic_indicator_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator_id text NOT NULL UNIQUE,
    indicator_name text NOT NULL,
    indicator_category text,
    unit text,
    frequency text,
    source_name text,
    is_active boolean NOT NULL DEFAULT true
);
