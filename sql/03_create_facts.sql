-- Fact table grains:
-- job_posting: one current posting; job_skill: one posting-skill pair;
-- admission: one university/major/admission-year record;
-- economic_indicator: one indicator/location/period observation;
-- labour_market: one location/period labour-market observation;
-- enterprise: one location/industry/period observation.
CREATE TABLE IF NOT EXISTS gold.fact_job_posting (
    job_posting_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id text NOT NULL UNIQUE,
    date_key integer REFERENCES gold.dim_date(date_key),
    company_key bigint REFERENCES gold.dim_company(company_key),
    occupation_key bigint REFERENCES gold.dim_occupation(occupation_key),
    industry_key bigint REFERENCES gold.dim_industry(industry_key),
    location_key bigint REFERENCES gold.dim_location(location_key),
    source_name text,
    job_title text NOT NULL,
    job_type text,
    experience_level text,
    education_level text,
    salary_min numeric(18,2),
    salary_max numeric(18,2),
    salary_currency char(3),
    salary_period text,
    is_salary_disclosed boolean NOT NULL DEFAULT false,
    posting_count smallint NOT NULL DEFAULT 1 CHECK (posting_count = 1),
    is_active boolean NOT NULL DEFAULT true,
    crawled_at timestamptz,
    valid_through date,
    CHECK (salary_min IS NULL OR salary_min >= 0),
    CHECK (salary_max IS NULL OR salary_max >= 0),
    CHECK (salary_min IS NULL OR salary_max IS NULL OR salary_max >= salary_min)
);

CREATE TABLE IF NOT EXISTS gold.fact_job_skill (
    job_posting_key bigint NOT NULL REFERENCES gold.fact_job_posting(job_posting_key) ON DELETE CASCADE,
    skill_key bigint NOT NULL REFERENCES gold.dim_skill(skill_key),
    evidence_field text NOT NULL CHECK (evidence_field IN ('requirements_raw', 'description_raw', 'skills_raw')),
    matched_text text NOT NULL,
    raw_skill_text text,
    is_required boolean,
    required_level text,
    years_required numeric(5,2) CHECK (years_required IS NULL OR years_required >= 0),
    extraction_method text NOT NULL,
    confidence_score numeric(5,4) CHECK (confidence_score BETWEEN 0 AND 1),
    validation_status text NOT NULL DEFAULT 'PENDING',
    extractor_version text,
    PRIMARY KEY (job_posting_key, skill_key)
);

CREATE TABLE IF NOT EXISTS gold.fact_admission (
    admission_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_year smallint NOT NULL,
    university_key bigint NOT NULL REFERENCES gold.dim_university(university_key),
    major_key bigint NOT NULL REFERENCES gold.dim_major(major_key),
    location_key bigint REFERENCES gold.dim_location(location_key),
    program_code text,
    degree_level text,
    admission_method text,
    target_count bigint CHECK (target_count IS NULL OR target_count >= 0),
    applicant_count bigint CHECK (applicant_count IS NULL OR applicant_count >= 0),
    admitted_count bigint CHECK (admitted_count IS NULL OR admitted_count >= 0),
    enrolled_count bigint CHECK (enrolled_count IS NULL OR enrolled_count >= 0),
    tuition_amount numeric(18,2) CHECK (tuition_amount IS NULL OR tuition_amount >= 0),
    tuition_currency char(3),
    source_name text,
    UNIQUE (admission_year, university_key, major_key, program_code, admission_method)
);

CREATE TABLE IF NOT EXISTS gold.fact_economic_indicator (
    economic_observation_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    economic_indicator_key bigint NOT NULL REFERENCES gold.dim_economic_indicator(economic_indicator_key),
    location_key bigint REFERENCES gold.dim_location(location_key),
    date_key integer REFERENCES gold.dim_date(date_key),
    period_start date NOT NULL,
    period_end date,
    period_label text,
    value numeric(24,6),
    unit text,
    source_name text,
    CHECK (period_end IS NULL OR period_end >= period_start),
    UNIQUE (economic_indicator_key, location_key, period_start, period_label)
);

CREATE TABLE IF NOT EXISTS gold.fact_labour_market (
    labour_market_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_key bigint REFERENCES gold.dim_location(location_key),
    date_key integer REFERENCES gold.dim_date(date_key),
    period_start date NOT NULL,
    period_end date,
    period_label text,
    population_count bigint CHECK (population_count IS NULL OR population_count >= 0),
    labor_force_count bigint CHECK (labor_force_count IS NULL OR labor_force_count >= 0),
    employed_count bigint CHECK (employed_count IS NULL OR employed_count >= 0),
    unemployed_count bigint CHECK (unemployed_count IS NULL OR unemployed_count >= 0),
    underemployed_count bigint CHECK (underemployed_count IS NULL OR underemployed_count >= 0),
    labor_force_rate numeric(9,4),
    employment_rate numeric(9,4),
    unemployment_rate numeric(9,4),
    underemployment_rate numeric(9,4),
    average_income numeric(18,2),
    income_currency char(3),
    source_name text,
    CHECK (period_end IS NULL OR period_end >= period_start),
    UNIQUE (location_key, period_start, period_label)
);

CREATE TABLE IF NOT EXISTS gold.fact_enterprise (
    enterprise_observation_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_key bigint REFERENCES gold.dim_location(location_key),
    industry_key bigint REFERENCES gold.dim_industry(industry_key),
    date_key integer REFERENCES gold.dim_date(date_key),
    period_start date NOT NULL,
    period_end date,
    period_label text,
    enterprise_count bigint CHECK (enterprise_count IS NULL OR enterprise_count >= 0),
    newly_registered_count bigint CHECK (newly_registered_count IS NULL OR newly_registered_count >= 0),
    suspended_count bigint CHECK (suspended_count IS NULL OR suspended_count >= 0),
    dissolved_count bigint CHECK (dissolved_count IS NULL OR dissolved_count >= 0),
    revenue numeric(24,2),
    revenue_currency char(3),
    source_name text,
    CHECK (period_end IS NULL OR period_end >= period_start),
    UNIQUE (location_key, industry_key, period_start, period_label)
);
